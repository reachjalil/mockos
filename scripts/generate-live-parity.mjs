#!/usr/bin/env node
/**
 * Renders the live-provider parity report from its manifest and divergence
 * ledger, and drift-checks the committed Markdown.
 *
 * This never asserts that parity holds. It asserts that the report honestly
 * describes whatever has and has not been captured, so absent evidence can
 * never read as present evidence.
 */
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const manifestPath = "docs/conformance/live-parity-manifest.json";
const ledgerPath = "docs/conformance/divergence-ledger.json";
const outputPath = "docs/conformance/live-parity.md";

const VERDICTS = new Set([
  "not-captured",
  "match",
  "known-divergence",
  "defect",
  "out-of-scope",
]);
const TIERS = new Set(["a", "b"]);
const ENFORCEMENT = new Set(["advisory", "enforcing"]);
/** A capture older than this is reported as stale. It still does not fail. */
const STALE_AFTER_DAYS = 90;

class ValidationError extends Error {
  constructor(messages) {
    super(messages.join("\n"));
    this.name = "ValidationError";
    this.code = "LIVE_PARITY_VALIDATION_ERROR";
  }
}

class DriftError extends Error {
  constructor(message) {
    super(message);
    this.name = "DriftError";
    this.code = "LIVE_PARITY_DRIFT";
  }
}

const read = async (relative) => readFile(resolve(root, relative), "utf8");

export const validate = (manifest, ledger) => {
  const failures = [];
  const seen = new Set();
  const ledgerIds = new Set(ledger.entries.map((entry) => entry.id));

  for (const [index, entry] of manifest.cases.entries()) {
    const label = `cases[${index}]`;
    if (typeof entry.id !== "string" || entry.id === "") {
      failures.push(`${label}.id must be a non-empty string.`);
      continue;
    }
    if (seen.has(entry.id)) failures.push(`${label}.id "${entry.id}" is duplicated.`);
    seen.add(entry.id);
    if (!VERDICTS.has(entry.status)) {
      failures.push(`${label}.status "${entry.status}" is not a known verdict.`);
    }
    if (!TIERS.has(entry.tier)) failures.push(`${label}.tier must be "a" or "b".`);
    if (!ENFORCEMENT.has(entry.enforcement)) {
      failures.push(`${label}.enforcement must be "advisory" or "enforcing".`);
    }
    // The whole point of the report: a case with no capture cannot claim one.
    if (entry.status === "not-captured" && entry.capturedAt !== null) {
      failures.push(`${label} is not-captured but carries a capturedAt.`);
    }
    if (entry.status !== "not-captured" && entry.status !== "out-of-scope") {
      if (typeof entry.capturedAt !== "string") {
        failures.push(`${label}.status "${entry.status}" requires a capturedAt date.`);
      }
    }
  }

  for (const [index, entry] of ledger.entries.entries()) {
    const label = `ledger.entries[${index}]`;
    if (typeof entry.id !== "string" || entry.id === "") {
      failures.push(`${label}.id must be a non-empty string.`);
    }
    if (typeof entry.intentional !== "boolean") {
      failures.push(`${label}.intentional must be a boolean.`);
    }
    if (typeof entry.reason !== "string" || entry.reason.trim() === "") {
      failures.push(`${label}.reason must explain the divergence.`);
    }
    if (entry.caseId !== "*" && !seen.has(entry.caseId)) {
      failures.push(`${label}.caseId "${entry.caseId}" is not a known case id.`);
    }
  }

  if (ledgerIds.size !== ledger.entries.length) {
    failures.push("ledger entry ids must be unique.");
  }
  if (failures.length > 0) throw new ValidationError(failures);
};

export const isStale = (capturedAt, now) => {
  if (typeof capturedAt !== "string") return false;
  const captured = Date.parse(capturedAt);
  if (Number.isNaN(captured)) return false;
  return now - captured > STALE_AFTER_DAYS * 24 * 60 * 60 * 1000;
};

export const render = (manifest, ledger, now) => {
  const counts = new Map();
  for (const verdict of VERDICTS) counts.set(verdict, 0);
  for (const entry of manifest.cases) {
    counts.set(entry.status, (counts.get(entry.status) ?? 0) + 1);
  }
  const total = manifest.cases.length;
  const compared =
    total - (counts.get("not-captured") ?? 0) - (counts.get("out-of-scope") ?? 0);

  const lines = [
    "# Live-provider parity",
    "",
    `Status: ${manifest.status}`,
    `Last reviewed: ${manifest.lastReviewed}`,
    "",
    "<!-- Generated by scripts/generate-live-parity.mjs. Do not edit by hand. -->",
    "",
    "This report compares mockOS against a real Entra or Okta tenant. It is advisory:",
    "it never blocks a release. A case with no live capture is recorded as",
    "`not-captured`, which is **not** a pass — absent evidence must never read as",
    "present evidence.",
    "",
    "## Summary",
    "",
    `- Cases defined: **${total}**`,
    `- Compared against a real tenant: **${compared}**`,
    `- Matching: **${counts.get("match") ?? 0}**`,
    `- Known divergences: **${counts.get("known-divergence") ?? 0}**`,
    `- Defects: **${counts.get("defect") ?? 0}**`,
    `- Not yet captured: **${counts.get("not-captured") ?? 0}**`,
    `- Ledgered divergences: **${ledger.entries.length}** ` +
      `(${ledger.entries.filter((entry) => entry.intentional).length} intentional, ` +
      `${ledger.entries.filter((entry) => !entry.intentional).length} tracked defects)`,
    "",
    "## Cases",
    "",
    "| Case | Provider | Tier | Area | Capability | Status | Enforcement | Captured |",
    "|---|---|---|---|---|---|---|---|",
  ];

  for (const entry of [...manifest.cases].sort((a, b) => a.id.localeCompare(b.id))) {
    const captured = entry.capturedAt
      ? `${entry.capturedAt}${isStale(entry.capturedAt, now) ? " (stale)" : ""}`
      : "—";
    lines.push(
      `| \`${entry.id}\` | ${entry.provider} | ${entry.tier} | ${entry.area} | ` +
        `${entry.capability} | \`${entry.status}\` | ${entry.enforcement} | ${captured} |`
    );
  }

  lines.push(
    "",
    "## Divergence ledger",
    "",
    "Every difference a live run finds must resolve to an entry here. An unledgered",
    "difference is reported as a defect. An entry with `intentional: false` is a known",
    "bug that is tracked but not yet fixed, and still reports as a defect.",
    "",
    "| Id | Provider | Case | Field | Intentional | Reason |",
    "|---|---|---|---|---|---|"
  );

  for (const entry of [...ledger.entries].sort((a, b) => a.id.localeCompare(b.id))) {
    lines.push(
      `| \`${entry.id}\` | ${entry.provider} | \`${entry.caseId}\` | \`${entry.field}\` | ` +
        `${entry.intentional ? "yes" : "no"} | ${entry.reason} |`
    );
  }

  lines.push(
    "",
    "## Out of scope",
    "",
    "mockOS does not implement these, so they bound the parity claim:",
    ""
  );
  for (const item of manifest.outOfScope) lines.push(`- ${item}`);
  lines.push("");

  return lines.join("\n");
};

const main = async () => {
  const check = process.argv.includes("--check");
  const manifest = JSON.parse(await read(manifestPath));
  const ledger = JSON.parse(await read(ledgerPath));
  validate(manifest, ledger);

  // Date.now() only affects the stale annotation, which is derived from
  // capturedAt values that are themselves committed.
  const rendered = render(manifest, ledger, Date.now());

  if (!check) {
    await writeFile(resolve(root, outputPath), rendered, "utf8");
    process.stdout.write(`WROTE ${outputPath}\n`);
    return;
  }

  let existing = "";
  try {
    existing = await read(outputPath);
  } catch {
    throw new DriftError(`${outputPath} is missing. Run pnpm live-parity:generate.`);
  }
  if (existing !== rendered) {
    throw new DriftError(`${outputPath} is stale. Run pnpm live-parity:generate.`);
  }
  process.stdout.write(
    `PASS  ${manifest.cases.length} live parity cases and ${ledger.entries.length} ledger entries are consistent\n`
  );
};

if (process.argv[1] && import.meta.filename === resolve(process.argv[1])) {
  main().catch((error) => {
    process.stderr.write(`${error.message}\n`);
    process.exit(error.code === "LIVE_PARITY_DRIFT" ? 3 : 2);
  });
}
